#!/usr/bin/env bash
# Optimises the storefront images in public/assets and regenerates the list of
# available thumbnails in src/data/imageThumbs.ts.
#
#   - Full-size files are capped at 1400px and re-encoded as progressive JPEG.
#     They are only used by the zoom views and the large editorial photos.
#   - Every image also gets a 720px thumbnail under public/assets/thumbs/,
#     which is what product cards, galleries and the cart load by default,
#     and a 200px one under public/assets/thumbs-small/ for gallery strips
#     and search results.
#
# Run it after adding or replacing a file in public/assets:
#
#   npm run images
#
# Requires ImageMagick (`convert`, `identify`). Safe to re-run: full-size files
# that are already within the limits are left untouched.
set -euo pipefail

cd "$(dirname "$0")/.."

ASSETS=public/assets
THUMBS=$ASSETS/thumbs
SMALL=$ASSETS/thumbs-small
MANIFEST=src/data/imageThumbs.ts
FULL_MAX=1400
FULL_MAX_BYTES=400000
THUMB_MAX=720
SMALL_MAX=200

command -v convert >/dev/null || { echo "ImageMagick is required" >&2; exit 1; }

paths=()
while IFS= read -r file; do
  rel=${file#"$ASSETS"/}
  paths+=("/assets/$rel")

  read -r width height < <(identify -format '%w %h\n' "$file" | head -n 1)
  bytes=$(wc -c < "$file")
  oversized=0
  if [ "$width" -gt "$FULL_MAX" ] || [ "$height" -gt "$FULL_MAX" ]; then oversized=1; fi
  # Heavy JPEGs are re-encoded even when their dimensions are fine. PNGs are lossless, so only resized.
  case "$file" in *.png) ;; *) if [ "$bytes" -gt "$FULL_MAX_BYTES" ]; then oversized=1; fi ;; esac
  if [ "$oversized" -eq 1 ]; then
    tmp=$(mktemp)
    case "$file" in
      *.png) convert "$file" -resize "${FULL_MAX}x${FULL_MAX}>" -strip "png:$tmp" ;;
      *) convert "$file" -resize "${FULL_MAX}x${FULL_MAX}>" -strip -interlace Plane -quality 80 "jpg:$tmp" ;;
    esac
    mv "$tmp" "$file"
    chmod 644 "$file"
    echo "optimised  $rel"
  fi

  thumb="$THUMBS/$rel"
  if [ ! -f "$thumb" ] || [ "$file" -nt "$thumb" ]; then
    mkdir -p "$(dirname "$thumb")"
    case "$file" in
      *.png) convert "$file" -resize "${THUMB_MAX}x${THUMB_MAX}>" -strip "png:$thumb" ;;
      *) convert "$file" -resize "${THUMB_MAX}x${THUMB_MAX}>" -strip -interlace Plane -quality 74 "jpg:$thumb" ;;
    esac
    echo "thumbnail  $rel"
  fi

  small="$SMALL/$rel"
  if [ ! -f "$small" ] || [ "$file" -nt "$small" ]; then
    mkdir -p "$(dirname "$small")"
    case "$file" in
      *.png) convert "$file" -resize "${SMALL_MAX}x${SMALL_MAX}>" -strip "png:$small" ;;
      *) convert "$file" -resize "${SMALL_MAX}x${SMALL_MAX}>" -strip -quality 72 "jpg:$small" ;;
    esac
  fi
done < <(find "$ASSETS" -type f \( -name '*.jpg' -o -name '*.jpeg' -o -name '*.png' \) -not -path "$THUMBS/*" -not -path "$SMALL/*" | sort)

{
  echo "// Generated by scripts/optimize-images.sh. Do not edit by hand."
  echo "// Paths in public/assets that have thumbnails under /assets/thumbs/ and /assets/thumbs-small/."
  echo "export const IMAGE_THUMBS: ReadonlySet<string> = new Set(["
  for p in "${paths[@]}"; do
    echo "  '$p',"
  done
  echo "]);"
} > "$MANIFEST"

echo "Wrote $MANIFEST (${#paths[@]} images)"
